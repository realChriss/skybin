import io
import json
import tarfile
import urllib.request
from pathlib import Path

from fontTools import subset

VERSION = "1.61.0"
ICONS = {
    "BACK": "arrow-left",
    "BUCKET": "database",
    "CHECK": "check",
    "CLOSE": "x",
    "COPY": "copy",
    "CRUMB": "chevron-right",
    "DOWNLOAD": "download",
    "EDIT": "pencil",
    "EXTERNAL": "external-link",
    "FILE": "file",
    "FOLDER": "folder",
    "FOLDER_OPEN": "folder-open",
    "GLOBE": "globe",
    "INFO": "info",
    "LINK": "link",
    "NEW_FOLDER": "folder-plus",
    "PAUSE": "pause",
    "PLAY": "play",
    "PLUS": "plus",
    "REFRESH": "refresh-cw",
    "SEARCH": "search",
    "SORT_ASC": "chevron-up",
    "SORT_DESC": "chevron-down",
    "TRASH": "trash-2",
    "UPLOAD": "upload",
    "UPLOAD_FOLDER": "folder-up",
    "WARNING": "triangle-alert",
}

ROOT = Path(__file__).resolve().parent.parent
url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz"
with urllib.request.urlopen(url) as r, tarfile.open(fileobj=io.BytesIO(r.read())) as tar:
    read = lambda name: tar.extractfile(f"package/{name}").read()
    font, codepoints, license = read("font/lucide.ttf"), read("font/codepoints.json"), read("LICENSE")

codepoints = json.loads(codepoints)
options = subset.Options()
options.layout_features = []
options.hinting = False
subsetter = subset.Subsetter(options)
f = subset.load_font(io.BytesIO(font), options)
subsetter.populate(unicodes=[codepoints[name] for name in ICONS.values()])
subsetter.subset(f)
f.save(ROOT / "assets" / "lucide.ttf")
(ROOT / "assets" / "lucide-LICENSE.txt").write_bytes(license)

lines = [f"//! Generated by scripts/icons.py from Lucide {VERSION}; edit the list there and rerun it.", ""]
lines += [f'pub const {const}: &str = "\\u{{{codepoints[name]:x}}}";' for const, name in ICONS.items()]
(ROOT / "src" / "ui" / "icons.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
